import fs from "node:fs/promises";
import path from "node:path";
import { CHAT_LINE_MAX_BYTES, MAX_CHAT_LINES, bindCommand, encodeMessage, execCommand, sanitizeForCfg, splitByBytes, unbindCommand, type EncodedMessage } from "../shared/cfgEncode";

export { CHAT_LINE_MAX_BYTES, MAX_CHAT_LINES, bindCommand, encodeMessage, execCommand, sanitizeForCfg, splitByBytes, unbindCommand };
export type { EncodedMessage };

const HEADER = "// Written by CS2 Chat Translator. Safe to delete.";
const IDLE_HEADER = "// Written by CS2 Chat Translator. Nothing is prepared: pressing the bound key does nothing.";
/** Both this app and the previous one start their cfg with one of these, so we only ever overwrite our own files. */
const OWN_HEADERS = ["// Written by CS2 Chat Translator", "// Auto-generated by CS2 Chat Translator"];

export type SayChannel = "all" | "team";

export function renderCfg(lines: string[], channel: SayChannel): string {
  const cmd = channel === "team" ? "say_team" : "say";
  return [HEADER, ...lines.map((l) => `${cmd} "${l}"`), ""].join("\r\n");
}

export interface WrittenCfg extends EncodedMessage {
  file: string;
}

/** Writes the cfg atomically (temp file + rename) so the game never `exec`s a half-written file. */
export async function writeChatCfg(opts: {
  cfgDir: string;
  fileName: string;
  text: string;
  channel: SayChannel;
}): Promise<WrittenCfg> {
  const encoded = encodeMessage(opts.text);
  if (encoded.lines.length === 0) throw new CfgError("empty-message");
  const dir = path.resolve(opts.cfgDir);
  const file = path.join(dir, opts.fileName);
  if (path.dirname(file) !== dir) throw new CfgError("bad-file-name");
  try {
    await fs.access(dir);
  } catch {
    throw new CfgError("cfg-dir-missing");
  }
  const content = renderCfg(encoded.lines, opts.channel);
  try {
    await atomicWrite(file, content);
  } catch (err) {
    throw new CfgError("cfg-write-failed", (err as Error).message);
  }
  return { ...encoded, file };
}

export class CfgError extends Error {
  constructor(
    readonly code: "empty-message" | "bad-file-name" | "cfg-dir-missing" | "cfg-write-failed",
    detail?: string,
  ) {
    super(detail ? `${code}: ${detail}` : code);
  }
}

/** A cfg that does nothing when executed: the state of "no message is prepared". */
export function idleCfgContent(): string {
  return [IDLE_HEADER, ""].join("\r\n");
}

export function isOwnCfg(content: string): boolean {
  const first = content.split(/\r?\n/, 1)[0] ?? "";
  return OWN_HEADERS.some((h) => first.startsWith(h));
}

export type NeutralizeResult = "created" | "cleared" | "already-idle" | "foreign" | "no-dir" | "failed";

/**
 * Makes sure pressing the bound key can only send what THIS session prepared. A message left over from an earlier run
 * (or from the previous version of the app) is replaced by the do-nothing cfg. A file that is not ours is never touched.
 */
export async function neutralizeCfg(cfgDir: string, fileName: string): Promise<NeutralizeResult> {
  const dir = path.resolve(cfgDir);
  const file = path.join(dir, fileName);
  if (path.dirname(file) !== dir) return "failed";
  try {
    await fs.access(dir);
  } catch {
    return "no-dir";
  }
  let existing: string | null = null;
  try {
    existing = await fs.readFile(file, "utf8");
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code !== "ENOENT") return "failed";
  }
  if (existing !== null) {
    if (!isOwnCfg(existing)) return "foreign";
    if (existing.startsWith(IDLE_HEADER)) return "already-idle";
  }
  try {
    await atomicWrite(file, idleCfgContent());
    return existing === null ? "created" : "cleared";
  } catch {
    return "failed";
  }
}

async function atomicWrite(file: string, content: string): Promise<void> {
  const tmp = `${file}.${process.pid}.tmp`;
  try {
    await fs.writeFile(tmp, content, "utf8");
    try {
      await fs.rename(tmp, file);
    } catch {
      // Some Windows setups refuse to replace a file another process has open; fall back to in-place write.
      await fs.writeFile(file, content, "utf8");
      await fs.rm(tmp, { force: true });
    }
  } catch (err) {
    await fs.rm(tmp, { force: true }).catch(() => undefined);
    throw err;
  }
}
